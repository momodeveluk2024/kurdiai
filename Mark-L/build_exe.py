"""
Build Mark-L into a standalone Windows application.

    python build_exe.py

Produces dist/MarkL/MarkL.exe plus its _internal/ folder. The user needs no
Python installed — the interpreter and every dependency ship inside the bundle.
That also permanently removes the "pip installed into a different Python than the
one that runs the app" failure, which is the most common install problem here.

This script:
  1. verifies the build environment,
  2. generates version_info.txt from branding.py so the Windows file-properties
     dialog carries the author and copyright,
  3. runs PyInstaller against MarkL.spec,
  4. copies LICENSE next to the exe and reports what still needs doing.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import branding  # noqa: E402

VERSION_INFO = HERE / "version_info.txt"
DIST = HERE / "dist" / "MarkL"


def _four_tuple(version: str) -> str:
    """Windows version resources need exactly four integers: 1.0.0 -> (1, 0, 0, 0)."""
    parts = [int(p) for p in version.split(".")]
    while len(parts) < 4:
        parts.append(0)
    return "({})".format(", ".join(str(p) for p in parts[:4]))


def write_version_info() -> None:
    """Generate the VSVersionInfo resource PyInstaller embeds into the .exe."""
    vt = _four_tuple(branding.VERSION)
    content = f'''# Generated by build_exe.py from branding.py — do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName',      {branding.AUTHOR!r}),
         StringStruct('FileDescription',  {branding.APP_TITLE + " — " + branding.APP_TAGLINE!r}),
         StringStruct('FileVersion',      {branding.VERSION!r}),
         StringStruct('InternalName',     {branding.APP_NAME!r}),
         StringStruct('LegalCopyright',   {branding.COPYRIGHT!r}),
         StringStruct('OriginalFilename', 'MarkL.exe'),
         StringStruct('ProductName',      {branding.APP_TITLE!r}),
         StringStruct('ProductVersion',   {branding.VERSION!r})]
      )
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
'''
    VERSION_INFO.write_text(content, encoding="utf-8")
    print(f"  version_info.txt  -> v{branding.VERSION}, (c) {branding.AUTHOR}")


def check_environment() -> bool:
    """Verify PyInstaller and the app's own dependencies are importable HERE."""
    ok = True

    try:
        import PyInstaller  # noqa: F401
        print(f"  PyInstaller       -> {PyInstaller.__version__}")
    except ImportError:
        print("  PyInstaller       -> MISSING")
        print(f"\n    Install it with:  \"{sys.executable}\" -m pip install pyinstaller\n")
        return False

    # PyInstaller bundles what THIS interpreter can import. If the deps live in a
    # different Python, the build silently produces a broken exe — same root cause
    # as the ModuleNotFoundError users hit when running from source.
    missing = []
    for mod in ("PyQt6", "sounddevice", "google.genai", "psutil", "cv2",
                "fastapi", "qrcode", "pycaw"):
        try:
            __import__(mod)
        except ImportError:
            missing.append(mod)

    if missing:
        ok = False
        print(f"  dependencies      -> MISSING: {', '.join(missing)}")
        print(f"\n    This interpreter is: {sys.executable}")
        print(f"    Install into THIS one:\n"
              f'      "{sys.executable}" -m pip install -r requirements.txt\n')
    else:
        print("  dependencies      -> all present")

    for required in ("main.py", "MarkL.spec", "branding.py",
                     "config/jarvis.ico", "core/prompt.txt"):
        if not (HERE / required).exists():
            print(f"  {required:<17} -> MISSING")
            ok = False

    return ok


def build() -> int:
    print(f"\n{'=' * 62}\n  Building {branding.APP_TITLE} v{branding.VERSION}\n{'=' * 62}\n")

    print("[1/4] Checking build environment...")
    if not check_environment():
        print("\nBuild aborted — fix the items above first.")
        return 1

    print("\n[2/4] Generating Windows version resource...")
    write_version_info()

    print("\n[3/4] Running PyInstaller (this takes several minutes)...")
    for stale in (HERE / "build", HERE / "dist"):
        if stale.exists():
            shutil.rmtree(stale, ignore_errors=True)

    result = subprocess.run(
        [sys.executable, "-m", "PyInstaller", "MarkL.spec", "--noconfirm", "--clean"],
        cwd=HERE,
    )
    if result.returncode != 0:
        print("\nPyInstaller failed. The output above shows why.")
        return result.returncode

    print("\n[4/4] Finalising...")
    if (HERE / "LICENSE").exists():
        shutil.copy2(HERE / "LICENSE", DIST / "LICENSE")

    exe = DIST / "MarkL.exe"
    if not exe.exists():
        print(f"  WARNING: expected {exe} but it is not there.")
        return 1

    size_mb = sum(f.stat().st_size for f in DIST.rglob("*") if f.is_file()) / (1024 * 1024)
    print(f"\n{'=' * 62}")
    print(f"  Build complete — {size_mb:.0f} MB")
    print(f"  {exe}")
    print(f"{'=' * 62}\n")
    print("  Right-click MarkL.exe -> Properties -> Details to see the")
    print(f"  copyright: {branding.COPYRIGHT}\n")
    print("  STILL TO DO before shipping to other people:")
    print("    * Playwright browsers are NOT bundled (they are ~400 MB and live in")
    print("      a per-user folder). browser_control's interactive actions will fail")
    print("      until 'playwright install' has run on the target machine.")
    print("    * The exe is unsigned, so SmartScreen will warn on first run.")
    print("      A code-signing certificate is the only real fix.")
    print("    * Test on a machine with NO Python installed — that is the whole")
    print("      point of the build, and the only way to catch a missing import.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(build())
